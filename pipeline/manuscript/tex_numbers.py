"""
Write pipeline-computed numbers straight into the Overleaf clone, so the
manuscript cites them via \\importnumber{key} instead of hand-copied digits.

All numbers live in one generated file, `numbers.tex` at the Overleaf clone
root, which main.tex pulls in once with `\\input{numbers}`. Each producing
script/notebook owns its own `% BEGIN <source>` ... `% END <source>` block
and only ever rewrites that block, so neuron_counts.ipynb and fig2.py (etc.)
can each update their own numbers without clobbering anyone else's.

Usage (from any manuscript script/notebook):

    import tex_numbers
    tex_numbers.write_numbers("neuron_counts", {
        "n_neurons_magnetic": 9797,
        "n_species": 7,
    })

then in LaTeX:  "we recorded \\importnumber{n_neurons_magnetic} neurons".

An undefined key renders as a bold ??key?? plus a LaTeX warning (like an
unresolved \\ref) rather than breaking the compile.

This only writes the file -- like sync_to_overleaf.py, it never commits or
pushes the Overleaf clone.
"""
import re
from pathlib import Path

OVERLEAF_CLONE = Path(__file__).resolve().parent / "64c94b448ce6028c013b0143"
NUMBERS_TEX = OVERLEAF_CLONE / "numbers.tex"

_KEY_RE = re.compile(r"^[A-Za-z0-9_]+$")
_BLOCK_RE = re.compile(r"^% BEGIN (\S+)\n(.*?)^% END \1\n", re.M | re.S)
_DEF_RE = re.compile(r"\\csname num@([A-Za-z0-9_]+)\\endcsname")

_HEADER = r"""% AUTO-GENERATED by pipeline/manuscript/tex_numbers.py -- do not edit by hand.
% Each block is rewritten by the script/notebook named in its BEGIN line;
% re-run that source to update its numbers.
\providecommand{\importnumber}[1]{%
  \ifcsname num@#1\endcsname\csname num@#1\endcsname
  \else\textbf{??\detokenize{#1}??}%
    \PackageWarning{numbers}{Number `\detokenize{#1}' undefined}\fi}
"""


def _format(value):
    if isinstance(value, bool):
        raise TypeError("bool is not a number")
    if isinstance(value, int) or (hasattr(value, "dtype") and value.dtype.kind in "iu"):
        return str(int(value))
    return str(value)  # floats/strings: caller is responsible for rounding/formatting


def write_numbers(source, values):
    """Replace `source`'s block in numbers.tex with `values` ({key: number})."""
    if not _KEY_RE.match(source):
        raise ValueError(f"source name must match {_KEY_RE.pattern}: {source!r}")
    for key in values:
        if not _KEY_RE.match(key):
            raise ValueError(f"key must match {_KEY_RE.pattern}: {key!r}")
    if not OVERLEAF_CLONE.is_dir():
        raise FileNotFoundError(f"Overleaf clone not found at {OVERLEAF_CLONE}")

    blocks = {}
    if NUMBERS_TEX.is_file():
        blocks = {m.group(1): m.group(2) for m in _BLOCK_RE.finditer(NUMBERS_TEX.read_text(encoding="utf-8"))}

    # A key defined by two different sources would silently shadow one of them.
    for other, body in blocks.items():
        clash = set(_DEF_RE.findall(body)) & set(values) if other != source else set()
        if clash:
            raise ValueError(f"keys {sorted(clash)} already defined by source {other!r}")

    blocks[source] = "".join(
        f"\\expandafter\\def\\csname num@{key}\\endcsname{{{_format(val)}}}\n"
        for key, val in values.items()
    )

    text = _HEADER + "".join(
        f"\n% BEGIN {name}\n{body}% END {name}\n" for name, body in sorted(blocks.items())
    )
    NUMBERS_TEX.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(values)} numbers for {source!r} -> {NUMBERS_TEX}")
